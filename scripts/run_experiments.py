#!/usr/bin/env python3
"""Run the 360-scenario experiment and regenerate paper artifacts."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from minpause.scenarios import generate_scenarios
from minpause.simulation import run_scenarios


def pct(value: float) -> str:
    return f"{100.0 * value:.1f}\\%"


def main() -> None:
    results_dir = ROOT / "results"
    figures_dir = ROOT / "figures"
    manuscript_dir = ROOT / "manuscript"
    results_dir.mkdir(exist_ok=True)
    figures_dir.mkdir(exist_ok=True)
    manuscript_dir.mkdir(exist_ok=True)

    scenarios = generate_scenarios(360)
    frame = pd.DataFrame(run_scenarios(scenarios))
    frame.to_csv(results_dir / "scenario_results.csv", index=False)

    metrics = [
        "attack_prevention_rate",
        "blocked_legitimate_fraction",
        "availability",
        "recovery_coverage",
        "bad_debt",
        "policy_size",
        "fairness_disparity",
    ]
    summary = frame.groupby("policy", sort=False)[metrics].agg(["mean", "std", "median"])
    summary.to_csv(results_dir / "summary.csv")

    means = frame.groupby("policy", sort=False)[metrics].mean()
    minpause = means.loc["MinPause"]
    global_freeze = means.loc["Global freeze"]
    manual = means.loc["Manual selective"]
    macros = "\n".join(
        [
            "% Auto-generated by scripts/run_experiments.py; do not edit.",
            f"\\newcommand{{\\ScenarioCount}}{{{len(scenarios)}}}",
            f"\\newcommand{{\\ExperimentRuns}}{{{len(frame):,}}}",
            f"\\newcommand{{\\MinAttackPrevention}}{{{pct(minpause['attack_prevention_rate'])}}}",
            f"\\newcommand{{\\MinBlockedVolume}}{{{pct(minpause['blocked_legitimate_fraction'])}}}",
            f"\\newcommand{{\\MinAvailability}}{{{pct(minpause['availability'])}}}",
            f"\\newcommand{{\\MinRecovery}}{{{pct(minpause['recovery_coverage'])}}}",
            f"\\newcommand{{\\GlobalBlockedVolume}}{{{pct(global_freeze['blocked_legitimate_fraction'])}}}",
            f"\\newcommand{{\\GlobalRecovery}}{{{pct(global_freeze['recovery_coverage'])}}}",
            f"\\newcommand{{\\ManualAttackPrevention}}{{{pct(manual['attack_prevention_rate'])}}}",
            f"\\newcommand{{\\MinPolicySize}}{{{minpause['policy_size']:.2f}}}",
            f"\\newcommand{{\\AvailabilityGain}}{{{pct(minpause['availability'] - global_freeze['availability'])}}}",
        ]
    )
    (manuscript_dir / "generated_macros.tex").write_text(macros + "\n", encoding="utf-8")

    policies = list(means.index)
    x = np.arange(len(policies))
    width = 0.26
    fig, ax = plt.subplots(figsize=(8.4, 4.2))
    ax.bar(x - width, means["attack_prevention_rate"], width, label="attack prevention")
    ax.bar(x, means["availability"], width, label="legitimate availability")
    ax.bar(x + width, means["recovery_coverage"], width, label="recovery coverage")
    ax.set_ylim(0, 1.05)
    ax.set_ylabel("Mean normalized outcome")
    ax.set_xticks(x, policies, rotation=18, ha="right")
    ax.grid(axis="y", alpha=0.25)
    ax.legend(ncol=3, frameon=False, loc="upper center")
    fig.tight_layout()
    fig.savefig(figures_dir / "policy_comparison.pdf", bbox_inches="tight")
    fig.savefig(figures_dir / "policy_comparison.png", dpi=220, bbox_inches="tight")
    plt.close(fig)

    min_rows = frame[frame.policy == "MinPause"].copy()
    fig, ax = plt.subplots(figsize=(7.5, 4.1))
    scatter = ax.scatter(
        min_rows["detection_delay_minutes"],
        min_rows["prevented_loss"] / 1_000_000,
        c=min_rows["price_shock"],
        s=18 + 45 * min_rows["attack_prevention_rate"],
        alpha=0.72,
        cmap="viridis",
        edgecolors="none",
    )
    ax.set_xlabel("Detection delay (minutes)")
    ax.set_ylabel("Prevented loss (million USD)")
    ax.grid(alpha=0.2)
    colorbar = fig.colorbar(scatter, ax=ax)
    colorbar.set_label("Collateral price shock")
    fig.tight_layout()
    fig.savefig(figures_dir / "robustness_surface.pdf", bbox_inches="tight")
    fig.savefig(figures_dir / "robustness_surface.png", dpi=220, bbox_inches="tight")
    plt.close(fig)

    print(f"Generated {len(frame)} policy evaluations from {len(scenarios)} scenarios")
    print(means.round(4).to_string())


if __name__ == "__main__":
    main()

